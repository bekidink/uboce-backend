// Regenerates docker-compose.yml from infrastructure/services.json so the
// service list lives in one place: node scripts/generate-compose.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const ports = JSON.parse(readFileSync(join(root, 'infrastructure', 'services.json'), 'utf8'));
const services = Object.keys(ports).filter((s) => s !== 'gateway');

const peerUrls = services.map((s) => `    ${s.toUpperCase()}_URL: http://${s}:${ports[s]}`).join('\n');

const serviceBlock = (name) => {
  const extra = {
    notification: ['      SMTP_URL: smtp://mailpit:1025'],
    document: ['      S3_ENDPOINT: http://seaweedfs:8333', '      # Signed links must use a host the client can reach.', '      S3_PUBLIC_ENDPOINT: http://localhost:8333'],
  }[name] ?? [];
  return `  ${name}:
    <<: *service
    build: { context: ., target: runtime, args: { TARGET: services/${name} } }
    env_file: services/${name}/.env
    environment:
      <<: *service-env
      DATABASE_URL: postgresql://${name}_svc:${name}_dev@postgres:5432/${name}
${extra.length ? `${extra.join('\n')}\n` : ''}    depends_on:
      migrate: { condition: service_completed_successfully }
`;
};

const yaml = `# GENERATED by scripts/generate-compose.mjs from infrastructure/services.json — edit those, not this.
name: uboce

# \`docker compose up -d\` starts infrastructure only (for \`pnpm dev\`).
# \`docker compose --profile apps up -d --build\` also runs every service in containers.

x-service: &service
  profiles: [apps]
  restart: unless-stopped
  depends_on:
    postgres: { condition: service_healthy }
    redis: { condition: service_healthy }
  environment: &service-env
    NODE_ENV: production
    REDIS_URL: redis://redis:6379
${peerUrls}

services:
  postgres:
    image: postgres:17-alpine
    environment:
      POSTGRES_USER: postgres
      POSTGRES_PASSWORD: postgres
    ports:
      - '5433:5432'
    volumes:
      - pgdata:/var/lib/postgresql/data
      - ./infrastructure/docker/postgres/init.sql:/docker-entrypoint-initdb.d/init.sql:ro
    healthcheck:
      test: ['CMD-SHELL', 'pg_isready -U postgres']
      interval: 5s
      timeout: 3s
      retries: 10

  redis:
    image: redis:7.4-alpine
    command: ['redis-server', '--appendonly', 'yes']
    ports:
      - '6380:6379'
    volumes:
      - redisdata:/data
    healthcheck:
      test: ['CMD', 'redis-cli', 'ping']
      interval: 5s
      timeout: 3s
      retries: 10

  # Catches every outgoing email locally. Inbox UI: http://localhost:8025
  mailpit:
    image: axllent/mailpit:v1.31.6
    ports:
      - '1025:1025'
      - '8025:8025'

  # Private S3-compatible storage for the Document service.
  seaweedfs:
    image: chrislusf/seaweedfs:4.48
    command: ['server', '-dir=/data', '-s3', '-s3.port=8333', '-s3.config=/etc/seaweedfs/s3.json', '-master.volumeSizeLimitMB=256']
    ports:
      - '8333:8333'
    volumes:
      - s3data:/data
      - ./infrastructure/docker/seaweedfs/s3.json:/etc/seaweedfs/s3.json:ro

  # ---- Application services (profile: apps) -------------------------------------
  # Migrations run as a one-shot container before the services start.

  migrate:
    <<: *service
    restart: 'no'
    build: { context: ., target: migrate }
    environment:
${services.map((s) => `      ${s.toUpperCase()}_DATABASE_URL: postgresql://${s}_svc:${s}_dev@postgres:5432/${s}`).join('\n')}

${services.map(serviceBlock).join('\n')}
  gateway:
    <<: *service
    build: { context: ., target: runtime, args: { TARGET: apps/gateway } }
    env_file: apps/gateway/.env
    environment:
      <<: *service-env
    ports:
      - '4100:4100'
    depends_on:
      identity: { condition: service_started }

volumes:
  pgdata:
  redisdata:
  s3data:
`;

writeFileSync(join(root, 'docker-compose.yml'), yaml);
console.log(`docker-compose.yml: ${services.length} services + gateway`);
