// Generates the single-server (VPS) deployment from infrastructure/services.json:
// pnpm vps:generate
//
// Writes (committed, no secrets):
//   deploy/vps/docker-compose.yml   all 22 services + Redis + SeaweedFS + migrations + Caddy
//   deploy/vps/Caddyfile            HTTPS: api.<domain> → gateway, files.<domain> → storage,
//                                   and optionally the web app's static build
// Service env files (with secrets) come from `pnpm vps:env`.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const ports = JSON.parse(readFileSync(`${root}infrastructure/services.json`, 'utf8'));

const out = `${root}deploy/vps`;
mkdirSync(out, { recursive: true });

const services = Object.keys(ports).filter((n) => n !== 'gateway');
const image = (name) => `\${IMAGE_PREFIX:-ghcr.io/bekidink/uboce}-${name}:\${TAG:-latest}`;
const health = (port) => `["CMD", "wget", "-qO-", "http://127.0.0.1:${port}/health/live"]`;

const app = (name, target, port, dependsOn) => `  ${name}:
    <<: *app
    image: ${image(name)}
    build:
      context: ../..
      target: runtime
      args:
        TARGET: ${target}
    env_file: env/${name}.env
    healthcheck:
      test: ${health(port)}
      interval: 15s
      timeout: 5s
      start_period: 40s
      retries: 5
    depends_on:
${dependsOn}`;

const blocks = [];
blocks.push(`  caddy:
    image: caddy:2.10-alpine
    restart: unless-stopped
    ports:
      - "80:80"
      - "443:443"
      - "443:443/udp"
    env_file: site.env
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - ./web:/srv/web:ro
      - caddy_data:/data
      - caddy_config:/config
    networks: [internal]
    logging: *logging
    depends_on:
      gateway:
        condition: service_healthy`);

blocks.push(`  redis:
    image: redis:7.4-alpine
    restart: unless-stopped
    # Event streams must survive restarts and must never be evicted.
    command: ["redis-server", "--appendonly", "yes", "--maxmemory-policy", "noeviction"]
    volumes:
      - redis_data:/data
    networks: [internal]
    logging: *logging
    healthcheck:
      test: ["CMD", "redis-cli", "ping"]
      interval: 10s
      timeout: 3s
      retries: 10`);

blocks.push(`  storage:
    image: ${image('storage')}
    build:
      context: ../../infrastructure/docker/seaweedfs
    restart: unless-stopped
    env_file: env/storage.env
    volumes:
      - storage_data:/data
    networks: [internal]
    logging: *logging`);

blocks.push(`  # Applies every service's pending migrations, then exits; services start after it.
  migrate:
    image: ${image('migrate')}
    build:
      context: ../..
      target: migrate
    restart: "no"
    env_file: env/migrate.env
    networks: [internal]
    logging: *logging`);

const serviceDeps = `      migrate:
        condition: service_completed_successfully
      redis:
        condition: service_healthy`;
for (const name of services) {
  let block = app(name, `services/${name}`, ports[name], serviceDeps + (name === 'document' ? '\n      storage:\n        condition: service_started' : ''));
  // Optional Firebase service-account key for push notifications, from deploy/vps/secrets/.
  if (name === 'notification') block = block.replace('    env_file: env/notification.env\n', '    env_file: env/notification.env\n    volumes:\n      - ./secrets:/run/secrets:ro\n');
  blocks.push(block);
}
blocks.push(app('gateway', 'apps/gateway', ports.gateway, `      redis:\n        condition: service_healthy\n${services.map((n) => `      ${n}:\n        condition: service_healthy`).join('\n')}`));

const compose = `# Generated by scripts/generate-vps.mjs — edit that script, then \`pnpm vps:generate\`.
# Single-server deployment of the UBOCE backend. See docs/DEPLOY-VPS.md.
name: uboce

x-logging: &logging
  driver: json-file
  options:
    max-size: 10m
    max-file: "5"

x-app: &app
  restart: unless-stopped
  networks: [internal]
  logging: *logging
  environment:
    # 22 Node processes share the server; keep each heap modest.
    NODE_OPTIONS: --max-old-space-size=256

services:
${blocks.join('\n\n')}

networks:
  # Only Caddy publishes ports. Services still reach the internet (Supabase, SMTP, Firebase).
  internal: {}

volumes:
  caddy_data: {}
  caddy_config: {}
  redis_data: {}
  storage_data: {}
`;
writeFileSync(`${out}/docker-compose.yml`, compose);

writeFileSync(
  `${out}/Caddyfile`,
  `# Generated by scripts/generate-vps.mjs. Domains come from site.env.
{
	email {$ACME_EMAIL}
}

# The API: only the gateway is exposed.
{$API_DOMAIN} {
	encode zstd gzip
	reverse_proxy gateway:${ports.gateway}
}

# Files: browsers upload and download with signed URLs, so the Host header must pass through unchanged.
{$FILES_DOMAIN} {
	request_body {
		max_size 110MB
	}
	reverse_proxy storage:8333
}

# The web app (uboce-web's dist/ copied to deploy/vps/web/), with client-side routing.
{$APP_DOMAIN} {
	encode zstd gzip
	root * /srv/web
	try_files {path} /index.html
	file_server
	header /assets/* Cache-Control "public, max-age=31536000, immutable"
}
`,
);

console.log(`deploy/vps: docker-compose.yml (${services.length + 1} app services + caddy, redis, storage, migrate) and Caddyfile`);

