// Writes each service's env file for the VPS deployment: pnpm vps:env
//
// Settings come from render.yaml (one list of every service's configuration),
// secrets from secrets/render.json (`pnpm deploy:secrets`), and domains from
// deploy/vps/site.env. Peers are addressed by their Compose service names.
// Output: deploy/vps/env/*.env (git-ignored; copied to the server by deploy.sh).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const require = createRequire(import.meta.url);
const yaml = require(require.resolve('js-yaml', { paths: [`${root}node_modules/.pnpm/node_modules`] }));
const ports = JSON.parse(readFileSync(`${root}infrastructure/services.json`, 'utf8'));
const blueprint = yaml.load(readFileSync(`${root}render.yaml`, 'utf8'));

if (!existsSync(`${root}secrets/render.json`)) {
  console.error('Run `pnpm deploy:secrets` first.');
  process.exit(1);
}
const secrets = JSON.parse(readFileSync(`${root}secrets/render.json`, 'utf8'));
const site = Object.fromEntries([...readFileSync(`${root}deploy/vps/site.env`, 'utf8').matchAll(/^([A-Z0-9_]+)=(.*)$/gm)].map((m) => [m[1], m[2].trim()]));
for (const key of ['API_DOMAIN', 'FILES_DOMAIN', 'APP_DOMAIN']) {
  if (!site[key] || site[key].includes('example.com')) console.warn(`warning: set ${key} in deploy/vps/site.env (now "${site[key] ?? ''}")`);
}
const appUrl = `https://${site.APP_DOMAIN}`;
const hasFirebase = existsSync(`${root}deploy/vps/secrets/firebase-service-account.json`);

const compose = (renderName) => renderName.replace(/^uboce-/, '');
/** Address of a Render resource inside the Compose network. */
function address(ref) {
  if (ref.type === 'keyvalue') return 'redis://redis:6379';
  const name = compose(ref.name);
  if (name === 'storage') return 'http://storage:8333';
  return `http://${name}:${ports[name]}`;
}

const VPS = {
  APP_BASE_URL: appUrl,
  CORS_ORIGINS: appUrl,
  S3_PUBLIC_ENDPOINT: `https://${site.FILES_DOMAIN}`,
  TRUST_PROXY_HOPS: '1', // Caddy
  FIREBASE_SERVICE_ACCOUNT_PATH: '/run/secrets/firebase-service-account.json',
  // Same region as the database is no longer a given on a VPS.
  INTERNAL_CALL_TIMEOUT_MS: site.INTERNAL_CALL_TIMEOUT_MS || '15000',
};

const dir = `${root}deploy/vps/env`;
mkdirSync(dir, { recursive: true });
const migrate = [];
let files = 0;
const missing = [];

for (const svc of blueprint.services) {
  if (svc.type === 'keyvalue') continue;
  const name = compose(svc.name);
  const lines = [`# ${name} — generated by scripts/vps-env.mjs. Contains secrets: never commit.`];
  for (const e of svc.envVars ?? []) {
    if (e.key === 'TARGET') continue; // a build argument, not runtime config
    let value;
    if (e.fromService) value = address(e.fromService);
    else if (e.sync === false) value = secrets[svc.name]?.[e.key] ?? '';
    else value = String(e.value ?? '');
    // Push notifications only when the Firebase key is provided (otherwise they're logged).
    if (e.key === 'FIREBASE_SERVICE_ACCOUNT_PATH' && !hasFirebase) continue;
    if (e.key in VPS) value = VPS[e.key];
    if (e.sync === false && !value) missing.push(`${name}.${e.key}`);
    if (value === '') continue;
    lines.push(`${e.key}=${value}`);
    if (e.key === 'MIGRATE_DATABASE_URL') migrate.push(`${name.toUpperCase()}_DATABASE_URL=${value}`);
  }
  writeFileSync(`${dir}/${name}.env`, `${lines.join('\n')}\n`, { mode: 0o600 });
  files++;
}
writeFileSync(`${dir}/migrate.env`, `# Session-pooler URLs for migrations — generated by scripts/vps-env.mjs. Never commit.\n${migrate.join('\n')}\n`, { mode: 0o600 });

console.log(`deploy/vps/env: ${files + 1} env files (${migrate.length} services migrate)`);
if (missing.length) console.log(`Empty, so left out (set them with pnpm deploy:secrets before going live): ${missing.join(', ')}`);
